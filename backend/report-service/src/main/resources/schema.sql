CREATE TABLE IF NOT EXISTS reports (
    id VARCHAR(80) PRIMARY KEY,
    owner VARCHAR(100) NOT NULL, author VARCHAR(120) NOT NULL,
    type VARCHAR(100) NOT NULL, process VARCHAR(100) NOT NULL,
    area VARCHAR(100) NOT NULL, shift VARCHAR(100) NOT NULL, notes VARCHAR(300) NOT NULL,
    latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    status VARCHAR(25) NOT NULL, attempts INTEGER DEFAULT 0 NOT NULL, supervisor_note VARCHAR(300)
);
CREATE TABLE IF NOT EXISTS report_weather (
    report_id VARCHAR(80) PRIMARY KEY REFERENCES reports(id) ON DELETE CASCADE,
    latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL, temperature_c DOUBLE PRECISION NOT NULL,
    humidity_percent INTEGER NOT NULL, wind_kmh DOUBLE PRECISION NOT NULL, weather_code INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
    seq BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    report_id VARCHAR(80) NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    occurred_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL, message VARCHAR(300) NOT NULL
);
CREATE TABLE IF NOT EXISTS attachments (
    report_id VARCHAR(80) NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    id VARCHAR(80) NOT NULL, name VARCHAR(200) NOT NULL, size_bytes BIGINT NOT NULL,
    media_type VARCHAR(30) NOT NULL, content BLOB NOT NULL, PRIMARY KEY(report_id, id)
);
